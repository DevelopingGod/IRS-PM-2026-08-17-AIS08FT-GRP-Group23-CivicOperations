"""Builds the static New York outline the portals draw: five simplified borough shapes in SVG.

Source: the outline around every real NYC 311 report location in data/processed/requests_real.parquet,
per borough. Official borough boundaries run out over the water and look like a jigsaw; report
locations follow the land, so the rivers and the harbour show as gaps.
Output: app/frontend/src/nycOutline.js, a few kilobytes, so the portals need no map service.
The same projection is written out, so the frontend can place any latitude and longitude.

Run: py 01_Application/app/scripts/build_nyc_outline.py
"""
import json
import math
from pathlib import Path

import pandas as pd
import shapely
from shapely.geometry import MultiPoint

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "processed" / "requests_real.parquet"
OUT = ROOT / "app" / "frontend" / "src" / "nycOutline.js"

W = 1000                                   # drawing width; height follows the city's shape
WEST, EAST, SOUTH, NORTH = -74.27, -73.69, 40.49, 40.92
K = math.cos(math.radians((SOUTH + NORTH) / 2))
H = round(W * (NORTH - SOUTH) / ((EAST - WEST) * K))


def xy(lon, lat):
    return round((lon - WEST) / (EAST - WEST) * W, 1), round((NORTH - lat) / (NORTH - SOUTH) * H, 1)


def ring(coords):
    pts = [xy(x, y) for x, y in coords]
    return "M" + "L".join(f"{x} {y}" for x, y in pts) + "Z"


r = pd.read_parquet(SRC, columns=["borough", "latitude", "longitude"]).dropna()
shapes = {}
for boro, pts in r.groupby("borough"):
    if boro not in ("MANHATTAN", "BROOKLYN", "QUEENS", "BRONX", "STATEN ISLAND"):
        continue
    pts = pts[(pts.longitude.between(WEST, EAST)) & (pts.latitude.between(SOUTH, NORTH))]
    hull = shapely.concave_hull(MultiPoint(list(zip(pts.longitude, pts.latitude))), ratio=0.04)
    geom = hull.buffer(0.0025).buffer(-0.0015).simplify(0.0009, preserve_topology=True)
    polys = getattr(geom, "geoms", [geom])
    parts = [ring(p.exterior.coords) for p in polys if p.area > 2e-6]
    c = geom.representative_point()
    shapes[boro] = {"d": "".join(parts), "label": xy(c.x, c.y)}

# Where people really live and report, for the 3D city's buildings: a fixed sample, so the
# drawing is the same on every build. Each point is [x, y, borough number in BOROUGH_ORDER].
BOROUGH_ORDER = ["MANHATTAN", "BROOKLYN", "QUEENS", "BRONX", "STATEN ISLAND"]
pts = r[r.borough.isin(BOROUGH_ORDER) & r.longitude.between(WEST, EAST) & r.latitude.between(SOUTH, NORTH)]
pts = pts.sample(n=min(1800, len(pts)), random_state=2026)
SAMPLE = [[*xy(lon, lat), BOROUGH_ORDER.index(b)] for lon, lat, b in zip(pts.longitude, pts.latitude, pts.borough)]

js = ("// Generated by 01_Application/app/scripts/build_nyc_outline.py from real NYC 311 report locations.\n"
      f"export const VIEW = {{ width: {W}, height: {H} }}\n"
      f"export const BOUNDS = {json.dumps({'west': WEST, 'east': EAST, 'south': SOUTH, 'north': NORTH})}\n"
      f"export const BOROUGHS = {json.dumps(shapes)}\n"
      f"export const BOROUGH_ORDER = {json.dumps(BOROUGH_ORDER)}\n"
      f"export const SAMPLE = {json.dumps(SAMPLE, separators=(',', ':'))}\n"
      "export function project(lat, lon) {\n"
      f"  return [((lon - BOUNDS.west) / (BOUNDS.east - BOUNDS.west)) * {W}, ((BOUNDS.north - lat) / (BOUNDS.north - BOUNDS.south)) * {H}]\n"
      "}\n")
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(js) // 1024} KB, boroughs {sorted(shapes)}")
